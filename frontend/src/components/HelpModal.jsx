export default function HelpModal({ onClose, role: roleProp }) {
  const user = useAuthStore(s => s.user)
  const [openId, setOpenId] = useState(null)
  const [search, setSearch] = useState('')

  const role = roleProp || user?.role || 'reg'

  const sections = role === 'manager' ? HELP_MANAGER
    : role === 'partner_doctor' ? HELP_PARTNER
    : HELP_ADMIN

  const roleLabel = role === 'manager' ? 'Системный администратор'
    : role === 'partner_doctor' ? 'Врач-партнёр'
    : 'Администратор клиники'

  const filtered = search.trim()
    ? sections.filter(s =>
        s.title.toLowerCase().includes(search.toLowerCase()) ||
        s.content.toLowerCase().includes(search.toLowerCase())
      )
    : sections

  const toggle = (id) => setOpenId(prev => prev === id ? null : id)

  return (
    <div className="fixed inset-0 z-[100] flex flex-col" style={{ background: 'rgba(0,0,0,0.6)' }}>
      {/* Backdrop */}
      <div className="flex-1 min-h-0" onClick={onClose} />

      {/* Panel — поднимается снизу */}
      <div className="bg-white dark:bg-gray-800 rounded-t-2xl shadow-2xl flex flex-col max-h-[90vh]">

        {/* Шапка */}
        <div className="flex items-center justify-between px-5 pt-5 pb-3 border-b border-gray-100 dark:border-gray-700 flex-shrink-0">
          <div>
            <h2 className="text-lg font-bold text-gray-800 dark:text-white">Справка</h2>
            <p className="text-xs text-gray-400 dark:text-gray-500 mt-0.5">Раздел: {roleLabel}</p>
          </div>
          <button
            onClick={onClose}
            className="w-8 h-8 flex items-center justify-center rounded-full bg-gray-100 dark:bg-gray-700 text-gray-500 dark:text-gray-300 hover:bg-gray-200 dark:hover:bg-gray-600 transition text-sm font-bold"
          >
            ✕
          </button>
        </div>

        {/* Поиск */}
        <div className="px-4 py-3 flex-shrink-0">
          <input
            type="text"
            placeholder="Найти в справке..."
            value={search}
            onChange={e => setSearch(e.target.value)}
            className="w-full border border-gray-200 dark:border-gray-600 bg-white dark:bg-gray-700 text-gray-800 dark:text-gray-100 placeholder-gray-400 dark:placeholder-gray-500 rounded-xl px-4 py-2.5 text-sm focus:outline-none focus:border-primary transition"
          />
        </div>

        {/* Секции */}
        <div className="overflow-y-auto flex-1 px-4 pb-6">
          {filtered.length === 0 ? (
            <div className="text-center py-10 text-gray-400 dark:text-gray-500 text-sm">
              Ничего не найдено по запросу «{search}»
            </div>
          ) : (
            filtered.map(section => (
              <HelpSection
                key={section.id}
                section={section}
                isOpen={openId === section.id}
                onToggle={() => toggle(section.id)}
              />
            ))
          )}

          {/* Контакты поддержки */}
          <div className="mt-4 bg-gray-50 dark:bg-gray-700 border border-gray-100 dark:border-gray-600 rounded-xl p-4 text-center">
            <p className="text-xs text-gray-500 dark:text-gray-400">
              Не нашли ответ?
            </p>
            <p className="text-sm font-medium text-primary mt-1">
              Обратитесь к вашему руководителю
            </p>
          </div>
        </div>
      </div>
    </div>
  )
}
